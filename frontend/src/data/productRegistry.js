/**
 * Resolves any cart item, product object, or raw ID into its authentic product title, image, and price.
 * Eliminates generic "Technical Outerwear Piece" placeholders and heals corrupted snapshots.
 */
export function resolveProduct(itemOrProduct) {
  if (!itemOrProduct) {
    return PRODUCT_CATALOG_REGISTRY["prod-crimson-puffer"];
  }

  // If item wraps product object: item.product
  const raw = itemOrProduct.product || itemOrProduct;

  const rawId = String(raw._id || raw.id || (typeof raw === "string" ? raw : "")).trim();
  const rawName = String(raw.name || raw.title || "").trim();
  const rawNameLower = rawName.toLowerCase();
  const rawIdLower = rawId.toLowerCase();

  const isCorrupted =
    !rawName ||
    rawNameLower === "technical outerwear piece" ||
    rawNameLower === "technical outerwear" ||
    rawNameLower === "outerwear piece";

  // 1. Direct ID match in registry
  if (rawId && PRODUCT_CATALOG_REGISTRY[rawId]) {
    const reg = PRODUCT_CATALOG_REGISTRY[rawId];
    return {
      ...reg,
      _id: rawId,
      id: rawId,
      name: !isCorrupted && raw.name ? raw.name : reg.name,
      title: !isCorrupted && (raw.title || raw.name) ? (raw.title || raw.name) : reg.title,
      image:
        !isCorrupted && raw.image && raw.image !== "/assets/cat_sale_pop.png"
          ? raw.image
          : reg.image,
      price: !isCorrupted && raw.price && raw.price !== 250 ? Number(raw.price) : reg.price,
      subtitle: reg.subtitle || raw.subtitle,
      category: reg.category || raw.category || "Technical Apparel",
    };
  }

  // 2. ID-based partial detection
  if (rawIdLower.includes("shoe") || rawIdLower.includes("sneaker") || rawIdLower.includes("runner")) {
    const reg = PRODUCT_CATALOG_REGISTRY["prod-shoe"];
    return {
      ...reg,
      _id: rawId || reg.id,
      id: rawId || reg.id,
      name: !isCorrupted && raw.name ? raw.name : reg.name,
      title: !isCorrupted && (raw.title || raw.name) ? (raw.title || raw.name) : reg.title,
      image: reg.image,
      price: reg.price,
    };
  }

  if (rawIdLower.includes("pant") || rawIdLower.includes("cargo") || rawIdLower.includes("tactical")) {
    const reg = PRODUCT_CATALOG_REGISTRY["prod-alpha-pants"];
    return {
      ...reg,
      _id: rawId || reg.id,
      id: rawId || reg.id,
      name: !isCorrupted && raw.name ? raw.name : reg.name,
      title: !isCorrupted && (raw.title || raw.name) ? (raw.title || raw.name) : reg.title,
      image: reg.image,
      price: reg.price,
    };
  }

  if (rawIdLower.includes("watch") || rawIdLower.includes("chronograph") || rawIdLower.includes("timepiece")) {
    const reg = PRODUCT_CATALOG_REGISTRY["prod-watch"];
    return {
      ...reg,
      _id: rawId || reg.id,
      id: rawId || reg.id,
      name: !isCorrupted && raw.name ? raw.name : reg.name,
      title: !isCorrupted && (raw.title || raw.name) ? (raw.title || raw.name) : reg.title,
      image: reg.image,
      price: reg.price,
    };
  }

  if (rawIdLower.includes("hoodie") || rawIdLower.includes("fleece")) {
    const reg = PRODUCT_CATALOG_REGISTRY["prod-hoodie"];
    return {
      ...reg,
      _id: rawId || reg.id,
      id: rawId || reg.id,
      name: !isCorrupted && raw.name ? raw.name : reg.name,
      title: !isCorrupted && (raw.title || raw.name) ? (raw.title || raw.name) : reg.title,
      image: reg.image,
      price: reg.price,
    };
  }

  if (rawIdLower.includes("base") || rawIdLower.includes("layer")) {
    const reg = PRODUCT_CATALOG_REGISTRY["prod-base-layer"];
    return {
      ...reg,
      _id: rawId || reg.id,
      id: rawId || reg.id,
      name: !isCorrupted && raw.name ? raw.name : reg.name,
      title: !isCorrupted && (raw.title || raw.name) ? (raw.title || raw.name) : reg.title,
      image: reg.image,
      price: reg.price,
    };
  }

  if (rawIdLower.includes("shirt")) {
    const reg = PRODUCT_CATALOG_REGISTRY["prod-shirt"];
    return {
      ...reg,
      _id: rawId || reg.id,
      id: rawId || reg.id,
      name: !isCorrupted && raw.name ? raw.name : reg.name,
      title: !isCorrupted && (raw.title || raw.name) ? (raw.title || raw.name) : reg.title,
      image: reg.image,
      price: reg.price,
    };
  }

  // 3. Name-based match (when rawName is authentic)
  if (!isCorrupted) {
    if (rawNameLower.includes("shoe") || rawNameLower.includes("sneaker") || rawNameLower.includes("runner")) {
      const reg = PRODUCT_CATALOG_REGISTRY["prod-shoe"];
      return { ...reg, ...raw, name: raw.name || reg.name, title: raw.title || reg.title, image: reg.image, price: raw.price || reg.price };
    }
    if (rawNameLower.includes("pant") || rawNameLower.includes("cargo") || rawNameLower.includes("tactical")) {
      const reg = PRODUCT_CATALOG_REGISTRY["prod-alpha-pants"];
      return { ...reg, ...raw, name: raw.name || reg.name, title: raw.title || reg.title, image: reg.image, price: raw.price || reg.price };
    }
    if (rawNameLower.includes("watch") || rawNameLower.includes("chronograph") || rawNameLower.includes("timepiece")) {
      const reg = PRODUCT_CATALOG_REGISTRY["prod-watch"];
      return { ...reg, ...raw, name: raw.name || reg.name, title: raw.title || reg.title, image: reg.image, price: raw.price || reg.price };
    }
    if (rawNameLower.includes("hoodie") || rawNameLower.includes("fleece")) {
      const reg = PRODUCT_CATALOG_REGISTRY["prod-hoodie"];
      return { ...reg, ...raw, name: raw.name || reg.name, title: raw.title || reg.title, image: reg.image, price: raw.price || reg.price };
    }
    if (rawNameLower.includes("shirt") || rawNameLower.includes("base layer") || rawNameLower.includes("tee")) {
      const isBase = rawNameLower.includes("base") || rawNameLower.includes("layer");
      const reg = isBase ? PRODUCT_CATALOG_REGISTRY["prod-base-layer"] : PRODUCT_CATALOG_REGISTRY["prod-shirt"];
      return { ...reg, ...raw, name: raw.name || reg.name, title: raw.title || reg.title, image: reg.image, price: raw.price || reg.price };
    }
    if (rawNameLower.includes("puffer") || rawNameLower.includes("jacket")) {
      const reg = PRODUCT_CATALOG_REGISTRY["prod-crimson-puffer"];
      return { ...reg, ...raw, name: raw.name || reg.name, title: raw.title || reg.title, image: reg.image, price: raw.price || reg.price };
    }

    // Authentic product with own image & price
    if (raw.image && raw.price) {
      return {
        ...raw,
        _id: rawId,
        id: rawId,
        name: raw.name || raw.title || "Technical Piece",
        title: raw.title || raw.name || "Technical Piece",
        price: Number(raw.price),
        image: raw.image,
      };
    }
  }

  // Fallback to crimson puffer
  return PRODUCT_CATALOG_REGISTRY["prod-crimson-puffer"];
}
